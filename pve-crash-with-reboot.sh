#!/usr/bin/env bash
#
# pve-crash-with-reboot.sh
#
# ВНИМАНИЕ / WARNING:
#   Этот скрипт предназначен ИСКЛЮЧИТЕЛЬНО для санкционированного,
#   деструктивного тестирования отказоустойчивости на ОДНОРАЗОВОЙ,
#   вложенной (nested) тестовой лаборатории Proxmox VE.
#
#   Скрипт вызывает НЕМЕДЛЕННУЮ панику ядра ("kernel panic") на ТЕКУЩЕМ
#   хосте, на котором он выполняется, С последующей попыткой автоматической
#   перезагрузки по таймауту паники ядра (kernel.panic > 0). "Резерв"
#   (reserve) здесь означает именно резервный вариант перезагрузки после
#   паники, а НЕ создание резервной копии данных.
#
#   Хост и все вложенные гостевые машины внутри него станут недоступны на
#   время паники и до завершения автоматической перезагрузки (если она
#   сработает). Автоматическая перезагрузка после паники ядра не гарантирована
#   на 100% и может не произойти в зависимости от конфигурации ядра/гипервизора.
#
#   Область действия ограничена ТОЛЬКО текущим (вложенным/nested) хостом
#   Proxmox VE и его гостями. Внешний (outer) гипервизор, соседние ВМ,
#   общее хранилище и резервные копии находятся ВНЕ области применения
#   этого скрипта и не должны быть затронуты, если вложенность настроена
#   правильно -- однако сам скрипт этого не проверяет и не гарантирует.
#
#   Данный скрипт НЕ создаёт резервных копий данных.
#
#   См. также: README-ru.md для полного описания, ограничений и
#   предварительных условий использования.
#
set -Eeuo pipefail

export PATH=/usr/sbin:/usr/bin:/sbin:/bin
export LC_ALL=C

readonly SCRIPT_NAME="pve-crash-with-reboot.sh"
readonly SYSRQ_TRIGGER=/proc/sysrq-trigger
readonly SYSRQ_ENABLE=/proc/sys/kernel/sysrq
readonly KERNEL_PANIC=/proc/sys/kernel/panic

# Таймаут (в секундах) после паники ядра, по истечении которого ядро
# попытается выполнить автоматическую перезагрузку. Должен быть > 0,
# чтобы включить попытку перезагрузки.
readonly PANIC_REBOOT_TIMEOUT_SEC=10

die() {
    echo "${SCRIPT_NAME}: ОШИБКА: $*" >&2
    exit 1
}

usage() {
    cat >&2 <<EOF
Использование: ${SCRIPT_NAME} [--dry-run|--execute]

  --dry-run   (по умолчанию) Показать цель и предупреждения, ничего не делать.
  --execute   Запросить подтверждение и, при его получении, вызвать панику
              ядра С последующей попыткой автоматической перезагрузки
              через ${PANIC_REBOOT_TIMEOUT_SEC} секунд после паники.

Без аргументов эквивалентно --dry-run.
EOF
    exit 2
}

# --- Разбор аргументов --------------------------------------------------
if [[ $# -gt 1 ]]; then
    usage
fi

MODE="${1:---dry-run}"

case "${MODE}" in
    --dry-run|--execute)
        ;;
    *)
        usage
        ;;
esac

# --- Проверка прав ------------------------------------------------------
if [[ "$(id -u)" -ne 0 ]]; then
    die "скрипт должен быть запущен от имени root."
fi

# --- Проверка необходимых утилит ----------------------------------------
for cmd in pveversion systemd-detect-virt hostname sleep; do
    command -v "${cmd}" >/dev/null 2>&1 || die "требуемая утилита не найдена: ${cmd}"
done

# --- Проверка контейнер/ВМ ----------------------------------------------
# ВАЖНО: эти проверки НЕ доказывают, что это вложенная (nested) тестовая
# лаборатория, и НЕ являются авторизацией на выполнение атаки. Они лишь
# исключают самый очевидный случай ошибочного запуска внутри LXC/OpenVZ
# контейнера, где нет собственного ядра для паники.
if systemd-detect-virt --container --quiet; then
    die "обнаружен контейнер (LXC/OpenVZ) -- скрипт предназначен только для ВМ."
fi

if ! systemd-detect-virt --vm --quiet; then
    die "виртуализация ВМ не обнаружена (systemd-detect-virt --vm). Отказ."
fi

if ! VIRT_TYPE="$(systemd-detect-virt)"; then
    VIRT_TYPE="неизвестно (systemd-detect-virt завершился с ошибкой, хотя --vm обнаружение прошло успешно)"
fi

# --- Проверка возможности записи в интерфейсы ядра ----------------------
# Эти проверки лишь подтверждают доступность файлов для записи, они также
# НЕ доказывают корректность вложенности и НЕ являются авторизацией цели.
if [[ ! -w "${SYSRQ_TRIGGER}" ]]; then
    die "${SYSRQ_TRIGGER} недоступен для записи."
fi

if [[ ! -w "${KERNEL_PANIC}" ]]; then
    die "${KERNEL_PANIC} недоступен для записи."
fi

HOSTNAME_CUR="$(hostname)"
PVE_VERSION="$(pveversion || true)"

print_target_info() {
    cat <<EOF
=========================================================================
Цель воздействия (ТЕКУЩИЙ хост, на котором выполняется этот скрипт):
  Имя хоста (hostname):        ${HOSTNAME_CUR}
  Обнаруженная виртуализация:  ${VIRT_TYPE}
  Версия Proxmox VE:           ${PVE_VERSION}

Вариант скрипта: pve-crash-with-reboot.sh (С попыткой автоматической
перезагрузки через ${PANIC_REBOOT_TIMEOUT_SEC} секунд после паники ядра;
"резерв" = резервный вариант перезагрузки, а НЕ резервная копия данных).

ПРЕДУПРЕЖДЕНИЕ:
  - Это действие вызовет панику ядра ("kernel panic") на ТЕКУЩЕМ хосте.
  - Хост станет недоступен НЕМЕДЛЕННО; ядро попытается выполнить
    автоматическую перезагрузку через ${PANIC_REBOOT_TIMEOUT_SEC} секунд после паники,
    но это не гарантировано (зависит от конфигурации гипервизора/ядра).
  - Все вложенные (nested) гостевые ВМ/контейнеры внутри этого хоста
    будут прерваны аварийно (interrupted).
  - Существует риск потери данных на этом хосте и его гостях.
  - Резервная копия данных НЕ создаётся этим скриптом.
  - Если автоматическая перезагрузка не сработает, потребуется РУЧНОЕ
    вмешательство (например, ручной сброс через консоль внешнего
    гипервизора).
  - Данные проверки (root, systemd-detect-virt, права на запись в /proc)
    НЕ доказывают, что это одноразовая вложенная тестовая лаборатория,
    и НЕ являются авторизацией на выполнение данного теста. Ответственность
    за корректность цели полностью лежит на операторе, запускающем скрипт.
=========================================================================
EOF
}

print_target_info

if [[ "${MODE}" == "--dry-run" ]]; then
    echo "Режим --dry-run: настройки не изменены, авария не вызвана. Выход."
    exit 0
fi

# --- Режим --execute -----------------------------------------------------
if [[ ! -t 0 ]]; then
    die "--execute требует интерактивного stdin (терминала) для подтверждения."
fi

CONFIRM_PHRASE="CRASH WITH REBOOT ${HOSTNAME_CUR}"

echo
echo "Для подтверждения введите ТОЧНО следующую фразу (с учётом регистра) и нажмите Enter:"
echo "  ${CONFIRM_PHRASE}"
echo

read -r -p "> " USER_INPUT || die "не удалось прочитать подтверждение."

if [[ "${USER_INPUT}" != "${CONFIRM_PHRASE}" ]]; then
    die "подтверждение не совпадает. Отмена, без изменений."
fi

echo "Подтверждение получено. Через 5 секунд будет вызвана паника ядра с попыткой автоматической перезагрузки через ${PANIC_REBOOT_TIMEOUT_SEC} секунд после паники..."
sleep 5

# Устанавливаем таймаут автоматической перезагрузки после паники ядра и
# проверяем, что значение действительно применилось.
echo "${PANIC_REBOOT_TIMEOUT_SEC}" > "${KERNEL_PANIC}"
ACTUAL_PANIC_VALUE="$(cat "${KERNEL_PANIC}")"
if [[ "${ACTUAL_PANIC_VALUE}" != "${PANIC_REBOOT_TIMEOUT_SEC}" ]]; then
    die "не удалось установить ${KERNEL_PANIC}=${PANIC_REBOOT_TIMEOUT_SEC} (текущее значение: ${ACTUAL_PANIC_VALUE}). Отмена без вызова паники."
fi
echo "Установлено ${KERNEL_PANIC}=${ACTUAL_PANIC_VALUE} (подтверждено чтением)."

# Включаем sysrq (на случай, если он ограничен) и вызываем панику ядра.
echo 1 > "${SYSRQ_ENABLE}"
echo c > "${SYSRQ_TRIGGER}"

# Если мы всё ещё выполняемся -- паника не произошла ожидаемым образом.
die "не удалось вызвать панику ядра через ${SYSRQ_TRIGGER}."
